#!/usr/bin/env python3
"""Write claude-skills/fix-ui-bug/digit-frontend-map.md: where things are in DIGIT-Frontend's HCM console.

Reads a git ref of a DIGIT-Frontend clone without checking anything out:
  build-code-map.py [--clone ~/DIGIT-Frontend] [--ref origin/console-dev]
Lists, per react19 module: route -> component -> file, the MDMS schemas the code reads (schema -> files), and the
redux slices of the app-configuration editor. Rerun it after big merges; the diagnosis reads the result first.
"""
import argparse, collections, datetime, os, re, subprocess, sys

ROOT = "health/micro-ui-react19/web/packages/modules"
OUT = os.path.join(os.path.dirname(os.path.dirname(os.path.realpath(__file__))), "claude-skills", "fix-ui-bug", "digit-frontend-map.md")


def git(clone, *args):
    return subprocess.run(["git", "-C", clone, *args], capture_output=True, text=True, check=True).stdout


def show(clone, ref, path):
    try:
        return git(clone, "show", f"{ref}:{path}")
    except subprocess.CalledProcessError:
        return ""


def resolve(base_dir, spec, files):
    """Turn a relative import into a repo file that exists at the ref."""
    p = os.path.normpath(os.path.join(base_dir, spec))
    for cand in (p, p + ".js", p + ".jsx", p + "/index.js", p + "/index.jsx"):
        if cand in files:
            return cand
    return p


def routes(clone, ref, module, files):
    index = f"{ROOT}/{module}/src/pages/employee/index.js"
    src = show(clone, ref, index)
    imports = {}
    for name, spec in re.findall(r'import\s+(\w+)\s+from\s+["\'](\.[^"\']+)["\']', src):
        imports[name] = spec
    for name, spec in re.findall(r'const\s+(\w+)\s*=\s*(?:React\.)?lazy\(\s*\(\)\s*=>\s*import\(\s*["\'](\.[^"\']+)["\']', src):
        imports[name] = spec
    out = []
    for path, comp in re.findall(r'<Route\s+path=\{?[`"\']([^`"\']+)[`"\']\}?\s+element=\{\s*<(\w+)', src, re.S):
        spec = imports.get(comp)
        out.append((path, comp, resolve(os.path.dirname(index), spec, files) if spec else "(defined in index.js or a shared package)"))
    return index, out


def schemas(clone, ref, module):
    found = collections.defaultdict(set)
    try:
        hits = git(clone, "grep", "-n", "-o", "-E", r"HCM-ADMIN-CONSOLE\.[A-Za-z]+|MODULE_CONSTANTS\}\.[A-Za-z]+", ref, "--", f"{ROOT}/{module}/src")
    except subprocess.CalledProcessError:
        return {}
    for line in hits.splitlines():
        _, path, lineno, match = line.split(":", 3)
        name = "HCM-ADMIN-CONSOLE." + match.split(".", 1)[1]
        found[name].add(f"{path.replace(ROOT + '/', '')}:{lineno}")
    return found


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--clone", default=os.environ.get("DIGIT_FRONTEND_DIR", os.path.expanduser("~/DIGIT-Frontend")))
    ap.add_argument("--ref", default="origin/console-dev")
    a = ap.parse_args()
    sha = git(a.clone, "rev-parse", "--short", a.ref).strip()
    files = set(git(a.clone, "ls-tree", "-r", "--name-only", a.ref, "--", ROOT).split())
    modules = sorted({f.split("/")[5] for f in files if f.count("/") > 5})
    lines = [
        "# DIGIT-Frontend map (HCM console, react19)",
        "",
        f"Generated by `automation/build-code-map.py` from `{a.ref}` @ `{sha}` on {datetime.date.today()}. Regenerate after "
        "big merges. Paths are relative to `" + ROOT + "/` unless they start with `health/`.",
        "",
        "## Where to start",
        "- Console URLs look like `/workbench-ui/employee/<module base>/<route>`. The campaign-manager base is `campaign`, e.g.",
        "  `/workbench-ui/employee/campaign/new-app-configuration-redesign` → route `new-app-configuration-redesign` below.",
        "- Which branch is live: the image tag of `workbench-ui` (e.g. `console-dev-<sha>`, from `envinfo.sh` with cluster",
        "  access). Without it, read `console-dev`, which qa has deployed lately, and say the build wasn't checked.",
        "- The legacy (non-react19) copies under `health/micro-ui/web/micro-ui-internals/packages/modules/` are not what",
        "  the redesigned console screens run.",
        "- App-configuration editor: `campaign-manager/src/pages/employee/NewAppConfiguration/`. Page config comes from",
        "  `TransformedFormConfig` (filters flow/project/page/module, `module` = the `flow` URL parameter). Field drawer:",
        "  `NewDrawerFieldComposer.js`. Label pairs: `LabelFieldPairConfig`, filtered by `modules[<module>].enabledPages`.",
        "",
    ]
    for module in modules:
        index, rts = routes(a.clone, a.ref, module, files)
        sch = schemas(a.clone, a.ref, module)
        if not rts and not sch:
            continue
        lines += [f"## {module}", ""]
        if rts:
            lines += [f"Routes (`{index.replace(ROOT + '/', '')}`):", "", "| route | component | file |", "|---|---|---|"]
            lines += [f"| `{p}` | {c} | `{f.replace(ROOT + '/', '')}` |" for p, c, f in rts]
            lines.append("")
        if sch:
            lines += ["MDMS schemas read in code (first places):", "", "| schema | where |", "|---|---|"]
            for name in sorted(sch):
                where = sorted(sch[name])
                lines.append(f"| `{name}` | {', '.join(f'`{w}`' for w in where[:4])}{f' (+{len(where) - 4} more)' if len(where) > 4 else ''} |")
            lines.append("")
    redux = sorted(f for f in files if "/NewAppConfiguration/redux/" in f)
    if redux:
        lines += ["## App-configuration redux slices", ""] + [f"- `{f.replace(ROOT + '/', '')}`" for f in redux] + [""]
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))
    print(f"wrote {OUT}: {len(modules)} modules from {a.ref}@{sha}")


if __name__ == "__main__":
    sys.exit(main())
